test('camp C# transactions preserve resources on insufficient money/materials, stale actions, full storage and full backpack',function()
    local camp=CS.ProjectY.Data.CampData();local bag=CS.ProjectY.Data.EquipmentData();local player=CS.ProjectY.Data.PlayerData();local clock=CS.ProjectY.Data.NarrativeData()
    for _,id in ipairs({81,82,83,31,91,92}) do bag.Grid:Define(id,1,1) end
    bag.Grid:Configure(3,1);bag:AddStack(81,8);bag:AddStack(82,4);bag:AddStack(83,4);camp:Open()
    local version=camp.Revision
    assert(camp:Upgrade(1,0,version,10,{81},{4},bag,player)=='金币不足')
    assert(camp.Revision==version and bag:CountItem(81)==8 and camp:GetLevel(1)==0)
    player:AddCoins(100)
    assert(camp:Upgrade(1,0,version,10,{81},{20},bag,player)~='')
    assert(player.Coins==100 and bag:CountItem(81)==8)
    assert(camp:Deposit(81,3,80,version,bag)=='');assert(bag:CountItem(81)==5 and camp:Stored(81)==3)
    assert(camp:Upgrade(1,0,version,10,{81},{4},bag,player)~='','A stale action cannot spend')
    assert(camp:Upgrade(1,0,camp.Revision,10,{81},{4},bag,player)=='')
    assert(camp:GetLevel(1)==1 and camp:Stored(81)==0 and bag:CountItem(81)==4 and player.Coins==90,'Warehouse must be consumed first')
    assert(camp:Deposit(81,4,3,camp.Revision,bag)~='' and bag:CountItem(81)==4)
    assert(camp:Enqueue(1,1,1,0,60,camp.Revision,2,{83},{2},bag,player)=='')
    version=camp.Revision
    assert(camp:Enqueue(1,1,1,0,60,version,2,{83},{2},bag,player)~='')
    assert(player.Coins==88 and bag:CountItem(83)==2 and camp.Revision==version)
    assert(camp:Claim(1,version,59,{31},{12},{'ammo'},bag)~='')
    assert(camp:Claim(1,version,60,{31},{12},{'ammo'},bag):find('背包空间不足'))
    assert(camp.JobCount==1 and bag:CountItem(31)==0 and player.Coins==88)
    assert(camp:Deposit(81,4,80,version,bag)=='')
    assert(camp:Claim(1,camp.Revision,60,{31},{12},{'ammo'},bag)=='')
    assert(camp.JobCount==0 and bag:CountItem(31)==12 and player.Coins==88)
    assert(camp:Claim(1,camp.Revision,60,{31},{12},{'ammo'},bag)~='')
    assert(camp:Withdraw(81,1,camp.Revision,'material',bag):find('背包空间不足') and camp:Stored(81)==4)
    assert(camp:Deposit(82,4,80,camp.Revision,bag)=='')
    assert(camp:Withdraw(81,1,camp.Revision,'material',bag)=='' and camp:Stored(81)==3 and bag:CountItem(81)==1)
    assert(camp:Wait(60,camp.Revision,clock)=='' and clock.Minutes==60)
    assert(camp:Wait(360,camp.Revision,clock)=='' and clock.Minutes==420)
    assert(camp:Wait(1440,camp.Revision,clock)=='' and clock.Minutes==1860)
    assert(camp:Wait(5,camp.Revision,clock)~='' and clock.Minutes==1860)
end)
test('actual first-aid kits and preparation potions can be purchased and failed purchases remain atomic',function()
    local shop=CS.ProjectY.Data.ShopData();local bag=CS.ProjectY.Data.EquipmentData();local player=CS.ProjectY.Data.PlayerData()
    for _,id in ipairs({91,92,81}) do bag.Grid:Define(id,1,1) end
    bag.Grid:Configure(1,1);player:AddCoins(100)
    for index,id in ipairs({91,92}) do
        bag:Clear();bag.Grid:Configure(1,1);bag:AddStack(81,1)
        shop:Open(shop:Refresh(1,1,1,1,0,{index},{id},{2},{10}))
        local money=player.Coins;local version=shop.Revision
        assert(shop:Buy(index,1,version,bag,player,'consumable',0,0,0):find('背包空间不足'))
        assert(player.Coins==money and shop.Active:Find(index).Count==2 and bag:CountItem(id)==0)
        bag:ConsumeStack(81,1)
        assert(shop:Buy(index,1,version,bag,player,'consumable',0,0,0)=='')
        assert(bag:CountItem(id)==1 and player.Coins==money-10 and shop.Active:Find(index).Count==1)
        assert(shop:Buy(index,1,version,bag,player,'consumable',0,0,0)~='');shop:Close()
    end
end)
