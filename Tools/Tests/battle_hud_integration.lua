local setup = assert(loadfile('Tools/Tests/battle_hud_fixture.lua'))()
local fixture = setup(Services)
local messages = {}
local function test(name, run) run(); messages[#messages+1]='PASS '..name end
local ok, err = xpcall(function()
    local hud,battle,ui,adapter=fixture.hud,fixture.battle,fixture.ui,fixture.adapter
    test('configured framework prefabs show real resources and blank icons',function()
        assert(hud.model.hp==battle:Active().HP)
        assert(hud.model.ap==battle:Active().AP and #hud.model.party==4 and #hud.model.turns==4 and hud.model.phase=='deployment')
        assert(not hud.actions[1].view.Icon.enabled and not hud.items[1].view.Icon.enabled)
        assert(hud.view.Round.text=='战前部署'and hud.view.EndTurnText.text=='结束部署')
        assert(not hud.items[1].view.Button.interactable and hud.items[2].view.Button.interactable)
        assert(not pcall(function() hud.view.HUD:SetIcon(hud.actions[1].view.Icon,1,'Assets/Unbound.png') end))
    end)
    test('button selection, resource refresh and cached reopen release their listeners',function()
        hud.actions[1].view.Button.onClick:Invoke();assert(adapter.SelectedBattleSkill==402 and adapter.selections==1)
        assert(battle:TrySkill(402,battle.data.ActiveId));ui:Tick(0,0)
        assert(hud.model.ap==2 and battle:Active().Effects:Find(402))
        hud.items[2].view.Button.onClick:Invoke();ui:Tick(0,0)
        assert(hud.model.ap==1 and fixture.data.Equipment:CountItem(92)==0 and not hud.items[2].view.Button.interactable)
        assert(#battle.Changed.listeners==1)
        ui:Close('BattleHUD');assert(#battle.Changed.listeners==0)
        hud=ui:Open('BattleHUD',{demo=adapter});assert(#battle.Changed.listeners==1)
        assert(#hud.model.skills==1 and hud.model.items[2].count==0)
    end)
    test('end-turn and automatic/manual AI controls use real turn ownership',function()
        for _=1,4 do assert(battle.data.Phase=='deployment');hud.view.EndTurn.onClick:Invoke();ui:Tick(0,0)end
        assert(battle.data.Phase=='combat'and hud.model.round==1 and hud.model.ap==4 and #hud.model.turns==7)
        assert(battle:Active().Effects:Find(402),'Preparation must survive the first combat turn start')
        hud.view.EndTurn.onClick:Invoke();ui:Tick(0,0)
        assert(not hud.model.player and not hud.view.EndTurn.interactable and not hud.view.Move.interactable)
        for _,action in ipairs(hud.actions) do assert(not action.view.Button.interactable) end
        hud.view.Auto.onClick:Invoke();ui:Tick(0,0);assert(hud.view.EndTurn.interactable and not adapter.BattleAutoAI)
        hud.view.EndTurn.onClick:Invoke();ui:Tick(0,0);assert(hud.model.player)
    end)
    test('all initiative cards remain reachable through the native horizontal scroll',function()
        local list=hud.turnList
        local scroll=list.scroll
        CS.UnityEngine.Canvas.ForceUpdateCanvases();list:Tick()
        assert(list.itemCount==#hud.model.turns and list.itemCount>4)
        assert(scroll.horizontal and not scroll.vertical and scroll.content.parent==scroll.viewport)
        assert(scroll.content.rect.width>scroll.viewport.rect.width and scroll.horizontalScrollbar.gameObject.activeSelf)
        for i,row in ipairs(hud.model.turns) do
            list:ScrollTo(i,1)
            local cell=assert(list:GetVisibleCell(i),'Every turn must be reachable, including the tail')
            assert(cell.widget.row.id==row.id)
            cell.widget.view.Button.onClick:Invoke();assert(adapter.focused==row.id)
        end
        local offset=scroll.content.anchoredPosition.x
        hud:Refresh();assert(math.abs(scroll.content.anchoredPosition.x-offset)<.1,'Content refresh must preserve the inspected position')
        list:ScrollTo(1,0);CS.UnityEngine.Canvas.ForceUpdateCanvases()
        local pointer=CS.UnityEngine.EventSystems.PointerEventData(CS.UnityEngine.EventSystems.EventSystem.current)
        pointer.scrollDelta=CS.UnityEngine.Vector2(0,-1)
        scroll:OnScroll(pointer)
        assert(scroll.content.anchoredPosition.x<0,'Vertical mouse wheel must scroll the horizontal queue')
        list:ScrollTo(1,0);CS.UnityEngine.Canvas.ForceUpdateCanvases()
        pointer.position=CS.UnityEngine.RectTransformUtility.WorldToScreenPoint(nil,scroll.viewport.position)
        scroll:OnInitializePotentialDrag(pointer);scroll:OnBeginDrag(pointer)
        pointer.position=pointer.position-CS.UnityEngine.Vector2(120,0)
        scroll:OnDrag(pointer);scroll:OnEndDrag(pointer)
        assert(scroll.content.anchoredPosition.x<0,'Dragging must reveal later cards')
        ui:Close('BattleHUD');hud=ui:Open('BattleHUD',{demo=adapter})
        CS.UnityEngine.Canvas.ForceUpdateCanvases();hud.turnList:Tick()
        assert(math.abs(hud.turnList.scroll.content.anchoredPosition.x)<.1)
        local first=assert(hud.turnList:GetVisibleCell(1));first.widget.view.Button.onClick:Invoke()
        assert(adapter.focused==hud.model.turns[1].id,'Cached reopen must keep the first card clickable')
    end)
    test('hide closes hover state and returns all battle subscriptions',function()
        hud.view.Tooltip.gameObject:SetActive(true);ui:Close('BattleHUD')
        assert(not hud.view.Tooltip.gameObject.activeSelf and #battle.Changed.listeners==0)
    end)

end,debug.traceback)
fixture.registry:Shutdown()
if not ok then error(err,0) end
return table.concat(messages,'\n')
