-- Run with isolated FrameworkServices after the single coordinated C# compilation and source-table export.
-- No user save files, scenes or Play lifecycle are opened by this fixture.
local registry=require('Core.SystemRegistry')(Services)
registry:Register('Config',require('Config.ConfigSystem'))
registry:Register('Battle',require('Game.Battle.BattleSystem'),{'Config'})
registry:Register('Equipment',require('Game.Equipment.EquipmentSystem'),{'Config'})
local results={};local function test(name,run)run();results[#results+1]='PASS '..name end
local ok,err=xpcall(function()
    registry:Start()
    local config=registry:Get('Config');local eq=registry:Get('Equipment');local rules=eq.rules
    local state=CS.ProjectY.Data.EquipmentCombatState;local conditions=CS.ProjectY.Data.EquipmentConditionData
    local function inventory(width,height)
        local data=CS.ProjectY.Data.EquipmentData();data.Grid:Configure(width,height)
        for _,item in ipairs(rules.items:All()) do data.Grid:Define(item.id,item.width,item.height) end
        return data
    end
    local area=CS.ProjectY.Data.MapAreaStateData(1,7,1)
    local session=CS.ProjectY.Data.LootSessionData()
    local function destination()
        area:AddLoot(1,102,'实体装备验证',{}, {},true)
        local container=area:GetLootAt(area.LootCount-1);session:Prepare(container,{}, {},{});return container
    end
    local data=inventory(12,10);local player=CS.ProjectY.Data.PlayerData()
    state.Initialize(data,901,2,0,{52},{'body'})
    local gun=data:Equipped(901);local armor=data:Worn(901,'body')
    local magazine=data:AddMagazine(21,31,12,7);assert(data:AttachMagazine(gun.Id,magazine.Id));data:SpendAmmo(gun.Id,1)
    local originalGunId,originalMagazineId=gun.Id,magazine.Id
    test('enemies receive real unique equipment without allocating backpack cells',function()
        assert(state.IsInitialized(data,901) and data.Grid.Count==0 and armor.OwnerActorId==901)
        assert(not pcall(function()state.Initialize(data,901,2,0,{},{})end),'An enemy loadout must not regenerate')
        state.Initialize(data,902,40,0,{51,52},{'head','body'})
        assert(data:Equipped(902).Id~=gun.Id and data:Worn(902,'body').Id~=armor.Id)
    end)
    test('half-threshold permanent loss occurs once until repaired; failed repairs are atomic',function()
        local condition=conditions.Of(gun)
        assert(condition.Current==100 and condition.Maximum==100)
        state.DamageWeapon(data,gun.Id,50);assert(condition.Current==50 and condition.Maximum==100)
        state.DamageWeapon(data,gun.Id,1);assert(condition.Current==49 and condition.Maximum==95 and not condition.ThresholdArmed)
        state.DamageWeapon(data,gun.Id,5);assert(condition.Current==44 and condition.Maximum==95)
        data:AddStack(83,20);local count,revision=data:CountItem(83),data.Revision
        assert(not state.Repair(data,player,'w'..gun.Id,83));assert(data:CountItem(83)==count and data.Revision==revision and condition.Current==44)
        player:AddCoins(1000);assert(state.Repair(data,player,'w'..gun.Id,83))
        assert(condition.Current==95 and condition.Maximum==95 and condition.ThresholdArmed and math.abs(condition.Efficiency-.95)<.00001)
        assert(data:CountItem(83)==count-3 and player.Coins==949)
        state.DamageWeapon(data,gun.Id,48);assert(condition.Current==47 and condition.Maximum==90)
        state.DamageWeapon(data,gun.Id,100);assert(condition.Broken and condition.Maximum==90)
        assert(state.Repair(data,player,'w'..gun.Id,83) and condition.Current==90 and condition.Maximum==90)
        assert(not pcall(function()conditions.Restore(80,75,100,true)end))
        assert(not pcall(function()conditions.Restore(10,95,100,true)end))
        assert(conditions.Restore(49,95,100,false).Current==49)
        local floorData=inventory(12,10);local worn=floorData:AddWeapon(40);floorData:AddStack(83,100)
        local payer=CS.ProjectY.Data.PlayerData();payer:AddCoins(10000)
        for i=1,20 do state.DamageWeapon(floorData,worn.Id,100);assert(state.Repair(floorData,payer,'w'..worn.Id,83)) end
        assert(conditions.Of(worn).Maximum==20 and conditions.Of(worn).Current==20)
    end)
    test('disarm moves the same weapon and loaded magazine; a full bag and repeated pickup cannot duplicate it',function()
        local container=destination();state.DropWeapon(data,area,container.Id,901,gun.Id)
        assert(not data:Equipped(901) and state.GroundWeapon(container)==gun and gun.OwnerActorId==0 and gun.Hand=='')
        assert(not pcall(function()data:GetWeapon(originalGunId)end) and not pcall(function()data:GetMagazine(originalMagazineId)end))
        session:Open(area,{container.Id},false,'验证','验证');local entry=session:GetAt(0)
        assert(conditions.Of(entry)==conditions.Of(gun))
        assert(not session:Take(data,entry.Key,0,0,false,0,0,0),'Unsearched equipment must not be received')
        session:Advance(entry.Key,2,1)
        local full=inventory(1,1);local revision=full.Revision
        assert(not session:Take(full,entry.Key,0,0,false,0,0,0) and full.Revision==revision and entry.Count==1)
        assert(session:Take(data,entry.Key,4,0,false,0,0,0))
        assert(data:GetWeapon(originalGunId)==gun and data:GetMagazine(originalMagazineId)==magazine and magazine.Rounds==6)
        assert(conditions.Of(gun).Current==90 and entry.Count==0 and container.Looted)
        revision=data.Revision;assert(not session:Take(data,entry.Key,4,0,false,0,0,0) and data.Revision==revision)
        session:Close()
    end)
    test('battle recovery bypasses bag capacity and corpse salvage transfers original damaged armor once',function()
        local empty=inventory(1,1);state.Initialize(empty,903,40,0,{52},{'body'})
        local blade=empty:Equipped(903);local body=empty:Worn(903,'body')
        local container=destination();state.DropWeapon(empty,area,container.Id,903,blade.Id)
        assert(state.RecoverWeapon(empty,area,container.Id,1,blade.Id))
        assert(empty:Equipped(1)==blade and container.Looted and not state.RecoverWeapon(empty,area,container.Id,2,blade.Id))
        state.DamageArmor(empty,903,100);assert(conditions.Of(body).Broken)
        local corpse=destination();state.DropActor(empty,area,corpse.Id,903)
        assert(not empty:Worn(903,'body'));session:Open(area,{corpse.Id},false,'尸体','原实例')
        local entry=session:GetAt(0);assert(entry.ItemId==52 and conditions.Of(entry).Broken)
        local count=session.Count;state.DropActor(empty,area,corpse.Id,903);assert(session.Count==count and corpse:GetCountAt(0)==1)
        local received=inventory(12,10);received:AddStack(83,8)
        session:Advance(entry.Key,2,1);assert(session:Take(received,entry.Key,7,0,false,0,0,0))
        assert(received:GetWearable(body.Id)==body and conditions.Of(body).Current==0)
        assert(state.Repair(received,player,'g'..body.Id,83) and conditions.Of(body).Current==95)
        session:Close()
    end)
    test('equipment maximum-health refresh never heals a wounded or defeated actor',function()
        local actor=CS.ProjectY.Data.CombatActorData(991,1);actor:SetMaxHP(40);actor:Restore();actor:Damage(10)
        state.RefreshMaximum(actor,50);assert(actor.HP==30 and actor.MaxHP==50)
        state.RefreshMaximum(actor,25);assert(actor.HP==5 and actor.MaxHP==25)
        actor:Damage(100);state.RefreshMaximum(actor,50);assert(actor.HP==0)
    end)
end,debug.traceback)
registry:Shutdown();if not ok then error(err) end
return table.concat(results,'\n')
