-- Actual inventory instances, learned skills and production workbench bindings in isolated services.
local registry=require('Core.SystemRegistry')(Services)
registry:Register('Config',require('Config.ConfigSystem'))
registry:Register('Battle',require('Game.Battle.BattleSystem'),{'Config'})
registry:Register('Equipment',require('Game.Equipment.EquipmentSystem'),{'Config'})
registry:Register('UI',require('UI.UISystem'),{'Config'})
local results={};local function test(name,run)run();results[#results+1]='PASS '..name end
local ok,err=xpcall(function()
    registry:Start()
    local adventure=Services.Adventure;adventure:Reset(712)
    local actor=adventure:AddPartyActor(1,3);actor:SetMaxHP(100);actor:Restore()
    actor.Growth:Initialize(17,12,2,0);actor.Growth:GrantSkill(103)
    local eq,battle,ui=registry:Get('Equipment'),registry:Get('Battle'),registry:Get('UI');eq:Start()
    local function weapon(item)
        for i=0,eq.data.WeaponCount-1 do local row=eq.data:GetWeaponAt(i);if row.ItemId==item then return row end end
        error('Missing configured starter weapon '..item)
    end
    local iron,knight,staff=weapon(40),weapon(41),weapon(1)
    test('actual equipment transaction rejects unmet attributes and accepts trained attributes',function()
        local revision=eq.data.Revision;local allowed,reason=eq:Command('equip',1,iron.Id,0,0)
        assert(not allowed and reason:find('属性不足') and eq.data.Revision==revision and not eq.data:Equipped(1))
        actor.Growth:InvestAttribute('strength',1,4)
        assert(eq:Command('equip',1,iron.Id,0,0));assert(eq.data:Equipped(1)==iron)
        local spell=battle:Skill(actor,103);assert(not eq.rules:CheckSkillEquipment(actor,spell,battle.stats))
        local found=false;for _,id in ipairs(battle:SkillIds(actor))do if id==103 then found=true end end
        assert(found and actor.Growth:HasSkill(103))
    end)
    test('offhand catalyst requires the real installed adapter and retained specialization',function()
        assert(eq:Command('equip_offhand',1,knight.Id,0,0))
        assert(eq:Command('attach',1,knight.Id,7,93));assert(knight:GetRune(7)==93 and eq.data:CountItem(93)==0)
        local spell=battle:Skill(actor,103);local allowed,reason=eq.rules:CheckSkillEquipment(actor,spell,battle.stats)
        assert(not allowed and reason:find('奥术兵装'))
        actor.Growth:UnlockTree(3);actor.Growth:InvestTalent(301,1)
        local selected;allowed,reason,selected=eq.rules:CheckSkillEquipment(actor,spell,battle.stats)
        assert(allowed and selected==knight)
        assert(eq:Command('attach',1,knight.Id,7,0));assert(not eq.rules:CheckSkillEquipment(actor,spell,battle.stats))
        assert(actor.Growth:HasSkill(103) and eq.data:CountItem(93)==1)
        assert(eq:Command('attach',1,knight.Id,7,93))
        local revision=eq.data.Revision;assert(not eq:Command('attach',1,iron.Id,6,11));assert(eq.data.Revision==revision)
    end)
    test('existing hand conflicts and native staff casting remain intact',function()
        assert(not eq:Command('equip',1,staff.Id,0,0))
        assert(eq:Command('unequip_offhand',1,0,0,0));assert(eq:Command('equip',1,staff.Id,0,0))
        local spell=battle:Skill(actor,103);assert(select(3,eq.rules:CheckSkillEquipment(actor,spell,battle.stats))==staff)
        assert(not eq:Command('equip_offhand',1,knight.Id,0,0))
        assert(eq:Command('unequip',1,0,0,0));assert(eq:Command('equip',1,iron.Id,0,0))
        assert(eq:Command('equip_offhand',1,knight.Id,0,0))
    end)
    test('production workbench displays the catalyst mount and does not mix in a real offhand',function()
        local adapter={SetEquipmentOpen=function(self,v)self.open=v end,SendCommand=function(_,command)assert(command=='snapshot')end}
        local panel=ui:Open('EquipmentWorkbench',{demo=adapter})
        panel.weaponId=iron.Id;panel:Refresh()
        assert(panel.socketId==6 and panel.view.SocketText1.text:find('触媒'))
        assert(panel.view.Stats.text:find('需要奥术触媒'),'Single-weapon preview must not borrow the real offhand catalyst')
        panel.weaponId=knight.Id;panel:Refresh()
        assert(panel.socketId==7 and panel.view.Stats.text:find('奥术触媒已就绪'))
        assert(eq.data:Equipped(1)==iron and eq.data:Offhand(1)==knight)
        ui:Close('EquipmentWorkbench');assert(not adapter.open and not Services.UI.IsWorldPaused)
    end)
end,debug.traceback)
registry:Shutdown();if not ok then error(err,0)end
return table.concat(results,'\n')
